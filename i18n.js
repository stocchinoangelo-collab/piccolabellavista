  const LINGUA_PREDEFINITA = "it";
  const CHIAVE_MEMORIA = "pbv-lingua";

  function leggiLinguaSalvata() {
    try { return window.localStorage.getItem(CHIAVE_MEMORIA); }
    catch (e) { return null; }
  }

  function salvaLingua(lingua) {
    try { window.localStorage.setItem(CHIAVE_MEMORIA, lingua); }
    catch (e) { /* navigazione privata: pazienza, non salviamo */ }
  }

  function applicaLingua(lingua) {
    const lang = translations[lingua] ? lingua : LINGUA_PREDEFINITA;
    const testi = translations[lang];

    /* 1. la lingua del documento: la leggono Google, i lettori per non
          vedenti e gli altri script del sito */
    document.documentElement.setAttribute("lang", lang);

    /* 2. i testi */
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const valore = testi[el.dataset.i18n];
      if (typeof valore === "string") el.textContent = valore;
    });

    /* 3. i testi grigi dentro i campi del modulo */
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const valore = testi[el.dataset.i18nPlaceholder];
      if (typeof valore === "string") el.setAttribute("placeholder", valore);
    });

    /* 4. i pulsanti IT / EN */
    document.querySelectorAll(".lang-button").forEach((b) => {
      const attivo = b.dataset.lang === lang;
      b.classList.toggle("active", attivo);
      b.setAttribute("aria-pressed", attivo ? "true" : "false");
    });

    salvaLingua(lang);
  }

  function avvia() {
    document.querySelectorAll(".lang-button").forEach((b) => {
      b.addEventListener("click", () => applicaLingua(b.dataset.lang));
    });
    const salvata = leggiLinguaSalvata();
    const attiva = document.querySelector(".lang-button.active");
    applicaLingua(salvata || attiva?.dataset.lang || LINGUA_PREDEFINITA);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", avvia, { once: true });
  } else {
    avvia();
  }
